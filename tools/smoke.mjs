import { chromium, firefox, webkit } from '@playwright/test';
import { resolve } from 'node:path';
const root = process.cwd();
const shots = process.argv[2];
const which = process.argv[3] ?? 'chromium';
const fixture = process.argv[4] ?? 'fixtures/real/glasgow/glasgow-kicad10.cad';
const bt = { chromium, firefox, webkit }[which];
const browser = await bt.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
const reqs = [];
page.on('request', (r) => reqs.push(r.url().slice(0, 120)));
await page.goto('file://' + resolve(root, 'dist/boardview.html'));
await page.waitForTimeout(500);
await page.screenshot({ path: `${shots}/${which}-empty.png` });
await page.setInputFiles('#bs-file-input', resolve(root, fixture));
await page.waitForSelector('[data-testid="file-name"]', { timeout: 20000 }).catch(() => logs.push('no file-name'));
await page.waitForTimeout(800);
await page.screenshot({ path: `${shots}/${which}-loaded.png` });
console.log(JSON.stringify({ logs, reqs: reqs.filter((u) => !u.startsWith('file://') && !u.startsWith('blob:') && !u.startsWith('data:')), allReqs: reqs.length }, null, 1));
await browser.close();
